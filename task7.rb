cosmetics = {
  "Мило" => 45.0,
  "Крем" => 120.0,
  "Тонік" => 150.0,
  "Скраб" => 95.0,
  "Шампунь" => 180.0,
  "Сироватка" => 320.0,
  "Бальзам для губ" => 80.0,
  "Маска для обличчя" => 210.0,
  "Гель для вмивання" => 0.0,
  "Лосьйон після гоління" => nil
}

puts "Спосіб 1 (використання sum):"
total1 = cosmetics.sum { |_, price| price.to_f }
puts "Загальна вартість усіх косметичних засобів: #{total1} грн"

puts "\nСпосіб 2 (використання each_value):"
total2 = 0.0
cosmetics.each_value do |price|
  total2 += price if price
end
puts "Загальна вартість усіх косметичних засобів: #{total2} грн"
